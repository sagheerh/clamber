#!/usr/bin/env python3
"""OWNER R25 one-time regeneration; normal baseline checker remains strict/unmodified.
Only accepts a fully verified triple/clock run whose SOLE failure is old baseline
mismatch. Not usable on an arbitrary source or as a retry of unequal replays.
"""
import json,os,subprocess,sys
from pathlib import Path


def regenerate(folder,out):
    report=json.loads((folder/'public-sim-summary.json').read_text())
    assert report['baseline_status'] in ('Committed baseline mismatch: FAIL, no tolerance/automatic update', 'Baseline must link a DECISIONS entry containing its exact generated hashes')
    old=json.loads(Path('tests/fixtures/public_sim_baseline.json').read_text())
    assert old['full_stream_sha256']=='05c27f020015dab2fc15ccad5cc963e5d064a8ed3247490a54e8f8ed57de1518'
    assert report['full_stream_sha256']!=old['full_stream_sha256']
    assert report['failures']==0 and report['attempt_started'] and report['replay_streams_byte_equal']
    assert all(r['failures']==0 for r in report['delivery'])
    head=subprocess.check_output(['git','rev-parse','HEAD'],text=True).strip()
    msg=subprocess.check_output(['git','log','-1','--format=%B'],text=True)
    assert '[R25-adopt]' in msg
    # Owner authorization is recorded in the SAME source commit, not inferred.
    assert '## M1-R25 — OWNER DECISION: P-B adoption' in Path('DECISIONS.md').read_text()
    b=json.loads((folder/'baseline-candidate.json').read_text())
    b.update(decision_id='M1-R25-BASELINE',source_head=head,
        source_ci_run=int(os.environ['GITHUB_RUN_ID']),source_job='r25-baseline',
        provenance='Owner R25 authorised regeneration on adoption source. Triple streams independently byte-equal; 30/144 clock streams equal. Normal public job reruns same commit against this explicit baseline overlay; generated baseline then committed without physics changes.')
    out.mkdir(parents=True,exist_ok=True)
    (out/'public_sim_baseline.json').write_text(json.dumps(b,indent=2)+'\n')
    provenance=f"\n\n## M1-R25-BASELINE — generated adopted-source replay provenance\n\nOwner R25 authorised regeneration, source {head}, CI{os.environ['GITHUB_RUN_ID']}.\nFinal digest {b['final_digest']}; full stream SHA256 {b['full_stream_sha256']};\nper-tick table SHA256 {b['per_tick_digest_table_sha256']}.\nGenerated from actual pinned4.7.2 triple streams+clock, not hand-edited expectation.\nSeparate public replay/clock job reruns this SAME source commit against generated\nbaseline; source overlay is explicit; closeout commits generated bytes/this entry.\n"
    (out/'provenance.md').write_text(provenance)
    print('M1 R25 generated baseline: '+json.dumps(b,separators=(',',':')))

if __name__=='__main__':regenerate(Path(sys.argv[1]),Path(sys.argv[2]))
